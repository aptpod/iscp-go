// Test_encoder_Golden pins the wire bytes. The golden files were generated by the
// gogo/protobuf based encoder; the encoder must keep producing identical bytes.
// Every map in the fixtures has at most one entry, so the output is deterministic.
func Test_encoder_Golden(t *testing.T) {
	for _, tt := range goldenCases() {
		t.Run(tt.name, func(t *testing.T) {
			path := filepath.Join("testdata", "golden", tt.name+".bin")
			testee := NewEncoding()

			var buf bytes.Buffer
			_, err := testee.EncodeTo(&buf, tt.msg)
			require.NoError(t, err)

			if *update {
				require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
				require.NoError(t, os.WriteFile(path, buf.Bytes(), 0o644))
			}

			golden, err := os.ReadFile(path)
			require.NoError(t, err)
			assert.Equal(t, golden, buf.Bytes())

			n, got, err := testee.DecodeFrom(bytes.NewReader(golden))
			require.NoError(t, err)
			assert.Equal(t, len(golden), n)
			assert.Equal(t, tt.msg, got)
		})
	}
}
